#!/usr/bin/env python3
"""The dependency graph: docs/DEPENDENCIES.md and docs/deps/.

  deps.py check <facts.json>   generate docs/DEPENDENCIES.md, docs/deps/claims.tsv and
                               docs/deps/{packages,modules,claims}.dot into a temporary directory,
                               render each .dot to .svg and .pdf with graphviz `dot`, and exit 1
                               if any committed file differs or is missing: byte for byte, except
                               that PDFs are compared by `pdf_norm` (cairo writes the time of
                               rendering into each, and the byte offsets move with its compressed
                               length)
  deps.py write <facts.json>   generate the same and replace the files that differ, so a PDF
                               that only re-rendering would change is kept

<facts.json> is written by `lake env lean --run scripts/Audit.lean --deps <facts.json>`: the packages
of the loaded modules, our modules and their imports, and for each claim the walk `closure` of
scripts/Audit.lean (its declarations of ours, its external constants by package, its axioms, its
TRUST ids from scripts/trust.tsv). Package revisions come from lake-manifest.json and the
requirements from each package's lakefile. The check also fails if the TRUST ids of docs/TRUST.md and
of scripts/trust.tsv differ.
"""
import json, os, re, shutil, subprocess, sys, tempfile, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = ["docs/DEPENDENCIES.md", "docs/deps/claims.tsv"] + [
    f"docs/deps/{g}.{x}" for g in ("packages", "modules", "claims") for x in ("dot", "svg", "pdf")]


def read(path):
    return open(os.path.join(ROOT, path), encoding="utf-8").read()


def bare(name):
    return name.strip("«»\"")


def requires(pkgdir):
    """The packages a lakefile requires, by name."""
    lean, toml = os.path.join(pkgdir, "lakefile.lean"), os.path.join(pkgdir, "lakefile.toml")
    if os.path.exists(lean):
        text = open(lean, encoding="utf-8").read()
        return [bare(m.group(1)) for m in re.finditer(
            r'^require\s+(?:"[^"]*"\s*/\s*)?("[^"]+"|«[^»]+»|[\w-]+)', text, re.M)]
    if os.path.exists(toml):
        text = open(toml, encoding="utf-8").read()
        return [bare(m.group(1)) for m in re.finditer(
            r'^\[\[require\]\]\s*\n(?:[^\[\n].*\n)*?name\s*=\s*"([^"]+)"', text, re.M)]
    return []


def packages(facts):
    """Rows (name, directory, revision, input revision, url, inherited) and requirement edges. The
    root is MojoProof; `lean4` is the toolchain, which every package uses."""
    man = json.loads(read("lake-manifest.json"))
    rows = [("MojoProof", "MojoProof", "this repository", "", "", False)]
    edges = [("MojoProof", bare(r)) for r in requires(ROOT)]
    for p in man["packages"]:
        name = bare(p["name"])
        rows.append((name, name, p["rev"], p.get("inputRev") or "", p["url"], p["inherited"]))
        edges += [(name, bare(r)) for r in requires(os.path.join(ROOT, man["packagesDir"], name))]
    rows.append(("lean4", "lean4", read("lean-toolchain").strip(), "", "", False))
    names = {r[0] for r in rows}
    unknown = sorted({b for _, b in edges} - names)
    if unknown:
        sys.exit(f"deps.py: required packages not in lake-manifest.json: {unknown}")
    return rows, sorted(set(edges))


def q(s):
    """A quoted graphviz ID; a newline becomes a line break of the label."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def trust_ids():
    """The TRUST ids of docs/TRUST.md and of scripts/trust.tsv, and the anchors."""
    doc = re.findall(r"^\| (T\d+) \|", read("docs/TRUST.md"), re.M)
    anchors = [l.split("\t") for l in read("scripts/trust.tsv").splitlines() if l.strip()]
    return doc, anchors


def short(module):
    return module.removeprefix("MojoProof.") if module != "MojoProof" else module


def generate(facts, out):
    os.makedirs(os.path.join(out, "docs/deps"), exist_ok=True)
    rows, edges = packages(facts)
    loaded = facts["packages"]
    doc_ids, anchors = trust_ids()
    tsv_ids = []
    for a in anchors:
        if a[0] not in tsv_ids:
            tsv_ids.append(a[0])
    if doc_ids != tsv_ids:
        sys.exit(f"deps.py: TRUST ids of docs/TRUST.md {doc_ids} differ from scripts/trust.tsv {tsv_ids}")
    md = []
    w = md.append
    w("# Dependencies\n")
    w("Generated by `scripts/deps.py` from the facts `scripts/Audit.lean --deps` writes; the gate")
    w("regenerates every file and fails if one differs (CONTRIBUTING.md). Do not edit by hand. The graphs")
    w("are `docs/deps/{packages,modules,claims}.dot`, rendered to `.svg` and `.pdf` with graphviz `dot`.\n")

    # (a) packages
    w("## Packages\n")
    w("Every package of `lake-manifest.json` with its exact revision; an edge is a `require` of the")
    w("package's lakefile. Loaded: how many of its modules the audit loads (our library and tests and")
    w("everything they import); a package with none is required but not imported by MojoProof.\n")
    w("| Package | Revision | Requested | Loaded modules | Requires |")
    w("|---|---|---|---|---|")
    for name, d, rev, inp, url, inh in rows:
        req = ", ".join(b for a, b in edges if a == name) or "-"
        w(f"| {name} | `{rev}` | {inp or '-'} | {loaded.get(d, 0)} | {req} |")
    w("")
    dot = ["digraph packages {", "  rankdir=LR;", '  node [shape=box, fontname="Helvetica"];']
    for name, d, rev, inp, url, inh in rows:
        n = loaded.get(d, 0)
        label = f"{name}\n{rev[:12] if re.fullmatch('[0-9a-f]{40}', rev) else rev}" + (f" ({inp})" if inp and inp != rev else "") + f"\n{n} modules loaded"
        style = ', style="dashed"' if n == 0 else ""
        dot.append(f"  {q(name)} [label={q(label)}{style}];")
    for a, b in edges:
        dot.append(f"  {q(a)} -> {q(b)};")
    dot.append("}")
    write(out, "docs/deps/packages.dot", "\n".join(dot) + "\n")

    # (b) modules
    mods = sorted(facts["modules"], key=lambda m: m["name"])
    for m in mods:
        m["imports"] = [ip for ip in m["imports"] if ip[0] != "Init"]
    ours = {m["name"] for m in mods}
    ext = {}
    for m in mods:
        for i, p in m["imports"]:
            if i not in ours:
                ext.setdefault(p, set()).add(i)
    w("## Modules\n")
    w("Every module of `GPUProof/`, `MojoProof/` and `MojoProofTest/` with its direct imports; external")
    w("imports are grouped by package. Every module also imports `Init`, Lean's prelude, which is not")
    w("listed.\n")
    w("| Module | Lines | Imports of ours | External imports |")
    w("|---|---|---|---|")
    for m in mods:
        imps = sorted({i for i, _ in m["imports"]})
        mine = ", ".join(short(i) for i in imps if i in ours) or "-"
        theirs = {}
        for i, p in m["imports"]:
            if i not in ours:
                theirs.setdefault(p, set()).add(i)
        other = "; ".join(f"{p}: " + ", ".join(sorted(s)) for p, s in sorted(theirs.items())) or "-"
        lines = len(read(m["name"].replace(".", "/") + ".lean").splitlines())
        w(f"| {m['name']} | {lines} | {mine} | {other} |")
    w("")
    dot = ["digraph modules {", "  rankdir=LR;", '  node [shape=box, fontname="Helvetica"];']
    for lib in ("GPUProof", "MojoProof", "MojoProofTest"):
        dot.append(f"  subgraph {q('cluster_' + lib)} {{ label={q(lib)};")
        for m in mods:
            if m["name"].split(".")[0] == lib:
                dot.append(f"    {q(m['name'])};")
        dot.append("  }")
    for p, s in sorted(ext.items()):
        dot.append(f"  subgraph {q('cluster_pkg_' + p)} {{ label={q('package ' + p)}; style=dashed;")
        for i in sorted(s):
            dot.append(f"    {q(i)} [shape=ellipse];")
        dot.append("  }")
    for m in mods:
        for i in sorted({i for i, _ in m["imports"]}):
            dot.append(f"  {q(m['name'])} -> {q(i)};")
    dot.append("}")
    write(out, "docs/deps/modules.dot", "\n".join(dot) + "\n")

    # (c) claims
    claims = sorted(facts["claims"], key=lambda c: c["name"])
    w("## Claims\n")
    w("The claims are the theorems among the audit targets (`scripts/targets.txt`). Each claim is")
    w("walked by `closure` (scripts/Audit.lean): the constants its statement and proof mention,")
    w("then those of every declaration of ours they reach (type and body), stopping at the first")
    w("external constant. Ours: the declarations of `GPUProof/` and `MojoProof/` reached,")
    w("auto-generated ones (matchers, equation lemmas, constructors, projections) not listed.")
    w("External: the external constants reached, by package. Axioms: every axiom reached through the")
    w("whole environment. TRUST: the ids of docs/TRUST.md whose anchor in `scripts/trust.tsv` the walk")
    w("reaches. The complete lists are in `docs/deps/claims.tsv` (claim, kind, module or package,")
    w("name).\n")
    w("TRUST anchors (`scripts/trust.tsv`): " + "; ".join(
        f"{a[0]} {a[1]}" + (f" `{a[2]}`" if len(a) > 2 and a[2] else "") for a in anchors) + ".\n")
    w("| Claim | Ours | External, by package | Axioms | TRUST |")
    w("|---|---|---|---|---|")
    tsv = []
    for c in claims:
        n = c["name"]
        exts = ", ".join(f"{p} {len(v)}" for p, v in sorted(c["external"].items()))
        w(f"| `{n}` | {len(c['ours'])} | {exts} | {', '.join(sorted(c['axioms']))} | "
          f"{', '.join(sorted(c['trust'], key=lambda t: int(t[1:])))} |")
        tsv += [(n, "ours", m, d) for d, m in c["ours"]]
        tsv += [(n, "external", p, x) for p, v in c["external"].items() for x in v]
        tsv += [(n, "axiom", "", a) for a in c["axioms"]]
        tsv += [(n, "trust", "", t) for t in c["trust"]]
    w("")
    w("### Declarations of ours reached, by module\n")
    for c in claims:
        w(f"**`{c['name']}`** (`{c['module']}`)\n")
        by = {}
        for d, m in c["ours"]:
            by.setdefault(m, []).append(d)
        for m, ds in sorted(by.items()):
            w(f"- {short(m)}: " + ", ".join(f"`{short(d)}`" for d in sorted(ds)))
        w("")
    write(out, "docs/deps/claims.tsv",
          "claim\tkind\tmodule or package\tname\n" + "".join("\t".join(r) + "\n" for r in sorted(set(tsv))))
    # Claims with the same modules, packages, axioms and TRUST ids share one node.
    groups = {}
    for c in claims:
        key = (tuple(sorted({m for _, m in c["ours"]})), tuple(sorted(c["external"])),
               tuple(sorted(c["axioms"])), tuple(sorted(c["trust"], key=lambda t: int(t[1:]))))
        groups.setdefault(key, []).append(c["name"])
    dot = ["digraph claims {", "  rankdir=LR;", "  concentrate=true;", '  node [fontname="Helvetica"];']
    targets = set()
    for k, (key, names) in enumerate(sorted(groups.items(), key=lambda g: g[1])):
        label = "\n".join(short(x).removeprefix("Sem.") for x in names)
        dot.append(f"  {q(f'claims{k}')} [shape=box, style=bold, label={q(label)}];")
        mods_, pkgs, axs, ts = key
        for t in [("module", m) for m in mods_] + [("package", p) for p in pkgs] + \
                 [("axiom", a) for a in axs] + [("trust", t) for t in ts]:
            targets.add(t)
            dot.append(f"  {q(f'claims{k}')} -> {q(t[0] + ' ' + t[1])};")
    shape = {"module": "ellipse", "package": "folder", "axiom": "diamond", "trust": "octagon"}
    for kind, name in sorted(targets):
        label = short(name) if kind == "module" else name
        dot.append(f"  {q(kind + ' ' + name)} [shape={shape[kind]}, label={q(label)}];")
    dot.append("}")
    write(out, "docs/deps/claims.dot", "\n".join(dot) + "\n")
    write(out, "docs/DEPENDENCIES.md", "\n".join(md).rstrip("\n") + "\n")
    for g in ("packages", "modules", "claims"):
        for x in ("svg", "pdf"):
            subprocess.run(["dot", f"-T{x}", os.path.join(out, f"docs/deps/{g}.dot"), "-o",
                            os.path.join(out, f"docs/deps/{g}.{x}")], check=True)


def write(out, path, text):
    with open(os.path.join(out, path), "w", encoding="utf-8") as f:
        f.write(text)


def pdf_norm(path):
    """What a PDF says, without the time of rendering: each stream's dictionary and decompressed
    contents, /CreationDate blanked; the cross-reference stream's dictionary without /Length and /W
    (not its byte offsets); and the bytes outside streams with only the stream lengths (the objects
    a /Length refers to) and the startxref offset blanked. Object references, page geometry and
    every other number are compared."""
    b = open(path, "rb").read()
    pat = re.compile(rb"(<<(?:(?!<<).)*?>>)\s*stream\r?\n(.*?)\r?\nendstream", re.S)
    streams = []
    for m in pat.finditer(b):
        if b"/Type /XRef" in m.group(1):
            streams.append((re.sub(rb"/(Length \d+|W \[[\d ]*\])", b"", m.group(1)), b""))
            continue
        try:
            body = zlib.decompress(m.group(2))
        except zlib.error:
            body = m.group(2)
        streams.append((m.group(1), re.sub(rb"/CreationDate \([^)]*\)", b"", body)))
    rest = pat.sub(b"", b)
    for n in set(re.findall(rb"/Length (\d+) 0 R", b)):
        rest = re.sub(rb"(?m)^(" + n + rb" 0 obj\s+)\d+", rb"\1#", rest)
    return streams, re.sub(rb"startxref\s+\d+", b"startxref #", rest)


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in ("write", "check"):
        sys.exit(__doc__)
    facts = json.load(open(sys.argv[2], encoding="utf-8"))
    tmp = tempfile.mkdtemp()
    try:
        generate(facts, tmp)
        stale = []
        for p in OUT:
            a, b = os.path.join(ROOT, p), os.path.join(tmp, p)
            if not os.path.exists(a):
                stale.append(p)
            elif p.endswith(".pdf"):
                if pdf_norm(a) != pdf_norm(b):
                    stale.append(p)
            elif open(a, "rb").read() != open(b, "rb").read():
                stale.append(p)
        if sys.argv[1] == "write":
            for p in stale:
                os.makedirs(os.path.dirname(os.path.join(ROOT, p)), exist_ok=True)
                shutil.copyfile(os.path.join(tmp, p), os.path.join(ROOT, p))
            print(f"wrote {len(stale)} of {len(OUT)} files")
            return
        for p in stale:
            print(f"stale: {p}" + ("" if os.path.exists(os.path.join(ROOT, p)) else " (missing)"))
        print(f"dependency graph: {len(OUT)} files, {len(stale)} stale")
        sys.exit(1 if stale else 0)
    finally:
        shutil.rmtree(tmp)


if __name__ == "__main__":
    main()
